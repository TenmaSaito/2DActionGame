//*************************************************************************************************

//*************************************************************************************************
//*** プロトタイプ宣言 ***
//*************************************************************************************************

//*************************************************************************************************
//*** グローバル変数 ***
//*************************************************************************************************
int g_nCounterResult;

//=================================================================================================
// --- タイトル関連cppファイルの初期化 ---
//=================================================================================================
void InitResult(void)
{
	g_nCounterResult = 0;

	/*** aの初期化 ***/

	/*** リザルト背景の初期化 ***/
	InitResultBg();

	/*** リザルトスコアの初期化 ***/
	InitResultScore();

	/*** リザルト背景の有効化 ***/
	SetEnableResultBg(true);

	/*** リザルトスコアの設定 ***/
	SetResultScore(D3DXVECTOR3(1300.0f, 550.0f, 0.0f), GetStarNum());
}

//=================================================================================================
// --- タイトル関連cppファイルの終了 ---
//=================================================================================================
void UninitResult(void)
{
	/*** aの終了 ***/

	/*** リザルトスコアの終了 ***/
	UninitResultScore();

	/*** リザルト背景の終了 ***/
	UninitResultBg();
}

//=================================================================================================
// --- タイトル関連cppファイルの更新 ---
//=================================================================================================
void UpdateResult(void)
{
	/*** aの更新 ***/

	/*** リザルト背景の更新 ***/
	UpdateResultBg();

	/*** リザルトスコアの更新 ***/
	UpdateResultScore();

	if ((GetKeyboardTrigger(DIK_RETURN)
		|| GetJoypadTrigger(JOYKEY_A)
		|| GetJoypadTrigger(JOYKEY_START))
		&& GetFade() == FADE_NONE)
	{
		SetFade(MODE_RANKING, FADE_TYPE_NORMAL, 120);

		/*** ゲームBGMをフェードイン ***/
		FadeSound(SOUND_LABEL_BGM_RESULT);
	}

	if (g_nCounterResult >= 600 && GetFade() == FADE_NONE)
	{
		SetFade(MODE_RANKING, FADE_TYPE_NORMAL, 120);

		/*** ゲームBGMをフェードイン ***/
		FadeSound(SOUND_LABEL_BGM_RESULT);
	}

	g_nCounterResult++;
}

//=================================================================================================
// --- タイトル関連cppファイルの描画 ---
//=================================================================================================
void DrawResult(void)
{
	/*** aの描画 ***/

	/*** リザルト背景の描画 ***/
	DrawResultBg();

	/*** リザルトスコアの描画 ***/
	DrawResultScore();
}