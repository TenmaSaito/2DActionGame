//=================================================================================================
// --- タイトル関連cppファイルの初期化 ---
//=================================================================================================
void InitResult(void)
{
	/*** aの初期化 ***/

	/*** リザルト背景の初期化 ***/
	InitResultBg();

	/*** リザルト背景の有効化 ***/
	SetEnableResultBg(true);
}

//=================================================================================================
// --- タイトル関連cppファイルの終了 ---
//=================================================================================================
void UninitResult(void)
{
	/*** aの終了 ***/

	/*** リザルト背景の終了 ***/
	UninitResultBg();
}

//=================================================================================================
// --- タイトル関連cppファイルの更新 ---
//=================================================================================================
void UpdateResult(void)
{
	/*** aの更新 ***/

	/*** リザルト背景の更新 ***/
	UpdateResultBg();

#if ENABLE_LOOP == true
	if (GetKeyboardTrigger(DIK_RETURN)
		&& GetFade() == FADE_NONE)
	{
		SetFade(MODE_TITLE, FADE_TYPE_NORMAL, 200);
	}
#endif
}

//=================================================================================================
// --- タイトル関連cppファイルの描画 ---
//=================================================================================================
void DrawResult(void)
{
	/*** aの描画 ***/

	/*** リザルト背景の描画 ***/
	DrawResultBg();
}