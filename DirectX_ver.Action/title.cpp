//=================================================================================================
// --- タイトル関連cppファイルの初期化 ---
//=================================================================================================
void InitTitle(void)
{
	/*** Aの初期化 ***/

	/*** 背景の初期化 ***/
	InitTitleBg();

	/*** 背景の有効化 ***/
	SetEnableTitleBg(true);
}

//=================================================================================================
// --- タイトル関連cppファイルの終了 ---
//=================================================================================================
void UninitTitle(void)
{
	/*** 背景の無効化 ***/
	SetEnableTitleBg(false);

	/*** Aの終了 ***/

	/*** 背景の終了 ***/
	UninitTitleBg();
}

//=================================================================================================
// --- タイトル関連cppファイルの更新 ---
//=================================================================================================
void UpdateTitle(void)
{
	/*** Aの更新 ***/

	/*** 背景の更新 ***/
	UpdateTitleBg();

#if ENABLE_LOOP == true
	if (GetKeyboardTrigger(DIK_RETURN)
		&& GetFade() == FADE_NONE)
	{
		SetFade(MODE_GAME, FADE_TYPE_NORMAL);
	}
#endif
}

//=================================================================================================
// --- タイトル関連cppファイルの描画 ---
//=================================================================================================
void DrawTitle(void)
{
	/*** Aの描画 ***/

	/*** 背景の描画 ***/
	DrawTitleBg();
}