//*************************************************************************************************

//**********************************************************************************
//*** プロトタイプ宣言 ***
//**********************************************************************************

//*************************************************************************************************
//*** グローバル変数 ***
//*************************************************************************************************
int g_nCounterTitle;

//=================================================================================================
// --- タイトル関連cppファイルの初期化 ---
//=================================================================================================
void InitTitle(void)
{
	g_nCounterTitle = 0;

	/*** Aの初期化 ***/

	/*** 背景の初期化 ***/
	InitTitleBg();

	/*** ロゴの初期化 ***/
	InitTitleLogo();

	/*** 背景の有効化 ***/
	SetEnableTitleBg(true);
}

//=================================================================================================
// --- タイトル関連cppファイルの終了 ---
//=================================================================================================
void UninitTitle(void)
{
	/*** 背景の無効化 ***/
	SetEnableTitleBg(false);

	/*** Aの終了 ***/

	/*** 背景の終了 ***/
	UninitTitleBg();

	/*** ロゴの終了 ***/
	UninitTitleLogo();
}

//=================================================================================================
// --- タイトル関連cppファイルの更新 ---
//=================================================================================================
void UpdateTitle(void)
{
	/*** Aの更新 ***/

	/*** 背景の更新 ***/
	UpdateTitleBg();

	/*** ロゴの更新 ***/
	UpdateTitleLogo();

	/*** 決定ボタンを押したとき ***/
	if (GetKeyboardTrigger(DIK_RETURN)
		&& GetFade() == FADE_NONE)
	{ // ゲーム画面へフェード
		/*** 決定音を鳴らす ***/
		PlaySound(SOUND_LABEL_SE_ENTER);
		SetFade(MODE_GAME, FADE_TYPE_NORMAL);

		/*** ゲームBGMをフェードイン ***/
		FadeSound(SOUND_LABEL_BGM_GAME);
	}

	if (g_nCounterTitle >= 600 && GetFade() == FADE_NONE)
	{
		SetFade(MODE_RANKING, FADE_TYPE_NORMAL);

		/*** ゲームBGMをフェードイン ***/
		FadeSound(SOUND_LABEL_BGM_RESULT);
	}

	g_nCounterTitle++;
}

//=================================================================================================
// --- タイトル関連cppファイルの描画 ---
//=================================================================================================
void DrawTitle(void)
{
	/*** Aの描画 ***/

	/*** 背景の描画 ***/
	DrawTitleBg();

	/*** ロゴの描画 ***/
	DrawTitleLogo();
}