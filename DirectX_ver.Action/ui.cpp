//================================================================================================================
// --- UI表示の表示処理 ---
//================================================================================================================
void SetUi(void)
{
	/*** ストック情報の設定 ***/
	SetUiStock(g_aUiData[0].pos, g_aUiData[0].fWidth, g_aUiData[0].fHeight);

	/*** 残機数表示の設定 ***/
	SetStockNum(10, g_aUiData[1].pos);
	
	/*** スター数情報の設定 ***/
	SetUiStar(g_aUiData[2].pos, g_aUiData[2].fWidth, g_aUiData[2].fHeight);

	/*** スター数表示の設定 ***/
	SetStarNum(0, g_aUiData[3].pos);

	/*** ステージ番号情報の設定 ***/
	SetUiStage(g_aUiData[4].pos, g_aUiData[4].fWidth, g_aUiData[4].fHeight);

	/*** ステージ番号表示の設定 ***/
	SetStageNum(1, g_aUiData[5].pos);
}