{
	/*** ストック情報の初期化 ***/
	InitUiStock();

	/*** 残機数表示の初期化 ***/
	InitStockNum();

	/*** スター数情報の初期化 ***/
	InitUiStar();

	/*** スター数表示の初期化 ***/
	InitStarNum();

	/*** ステージ番号情報の初期化 ***/
	InitUiStage();

	/*** ステージ番号表示の初期化 ***/
	InitStageNum();
}

//================================================================================================================
