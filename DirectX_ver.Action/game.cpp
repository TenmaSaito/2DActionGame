//================================================================================================================
// --- ステージ終了処理 ---
//================================================================================================================
void SetEndStage(void)
{
	if (g_gameState == GAMESTATE_NORMAL)
	{
		SetGameState(GAMESTATE_CLEAREND, 60);
	}
}

//================================================================================================================
// --- ゲーム状態の設定処理 ---
//================================================================================================================
void SetGameState(GAMESTATE state, int nCounter)
{
	g_gameState = state;

	g_nCounterState = nCounter;
}