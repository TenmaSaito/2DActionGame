//================================================================================================================
// --- ゲーム関連cppファイルの更新 ---
//================================================================================================================
void UpdateGame(void)
{
	switch (g_gameState)
	{
	case GAMESTATE_NONE:

		break;

	case GAMESTATE_NORMAL:

		break;

	case GAMESTATE_CLEAREND:

		g_nCounterState--;
		if (g_nCounterState <= 0)
		{
			if (GetFade() == FADE_NONE)
			{
				SetFade(MODE_RESULT, FADE_TYPE_NORMAL);
			}
		}

		break;
	}

	if (g_bPause == false)
	{
		/*** プレイヤーの更新 ***/
		UpdatePlayer();

		/*** ブロックの更新 ***/
		UpdateBlock();

		/*** アイテムの更新 ***/
		UpdateItem();

		/*** 敵の更新 ***/
		UpdateEnemy();

		/*** エフェクトの更新 ***/
		UpdateEffect();

		/*** パーティクルの更新 ***/
		UpdateParticle();

		/*** 出口の更新 ***/
		UpdateExit();

		/*** 背景の更新 ***/
		UpdateGameBg();
	}
#if ENABLE_LOOP == true
	if (GetKeyboardTrigger(DIK_RETURN)
		&& GetFade() == FADE_NONE)
	{
		SetFade(MODE_RESULT, FADE_TYPE_NORMAL);
	}
#endif
}

