//================================================================================================================
// --- ステージ終了処理 ---
//================================================================================================================
void SetEndStage(void)
{
	int nStage = GetStage();

	nStage++;

	/*** ゲームの状態が通常の時に判定 ***/
	if (g_gameState == GAMESTATE_NORMAL)
	{
		if ((nStage >= GetStageMax()))
		{
			/*** ゲームの状態をクリアに設定 ***/
			SetGameState(GAMESTATE_CLEAREND, 60);

			/*** 現在のステージ番号をリセットする ***/
			SetStageExac(0);
		}
		else
		{
			AddStageNum(1);

			ResetStage(false);

			/*** 現在のステージ番号を進める ***/
			SetStage(nStage);
		}
	}
}

