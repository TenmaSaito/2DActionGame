// --- ゲーム関連cppファイルの更新 ---
//================================================================================================================
void UpdateGame(void)
{
	/*** ゲームの状態により処理を変更 ***/
	switch (g_gameState)
	{
	// 何もなし
	case GAMESTATE_NONE:

		break;

	// 通常状態
	case GAMESTATE_NORMAL:

		break;

	// ゲームクリア
	case GAMESTATE_CLEAREND:

		g_nCounterState--;
		if (g_nCounterState <= 0)
		{
			if (GetFade() == FADE_NONE)
			{ // リザルト画面へ移行
				SetFade(MODE_RESULT, FADE_TYPE_NORMAL);
				FadeSound(SOUND_LABEL_BGM_RESULT);
			}
		}

		break;

	// ゲームオーバー
	case GAMESTATE_BADEND:

		g_nCounterState--;
		if (g_nCounterState <= 0)
		{
			if (GetFade() == FADE_NONE)
			{ // リザルト画面へ移行
				SetFade(MODE_RESULT, FADE_TYPE_NORMAL);
				FadeSound(SOUND_LABEL_BGM_RESULT);
			}
		}

		break;
	}
	
	/*** ゲーム状態が通常なら ***/
	if (g_gameState == GAMESTATE_NORMAL)
	{
		/*** ポーズボタンを押したとき ***/
		if (GetKeyboardTrigger(DIK_P)
			|| GetJoypadTrigger(JOYKEY_START))
		{
			g_bPause = g_bPause ^ true;
		}
	}

	/*** ポーズ状態でなければ更新 ***/
	if (g_bPause == false)
	{
		/*** プレイヤーの更新 ***/
		UpdatePlayer();

		/*** ブロックの更新 ***/
		UpdateBlock();

		/*** アイテムの更新 ***/
		UpdateItem();

		/*** 敵の更新 ***/
		UpdateEnemy();

		/*** エフェクトの更新 ***/
		UpdateEffect();

		/*** パーティクルの更新 ***/
		UpdateParticle();

		/*** 出口の更新 ***/
		UpdateExit();

		/*** 背景の更新 ***/
		UpdateGameBg();

		/*** UIの更新 ***/
		UpdateUi();

		/*** 重力反転時演出の更新 ***/
		UpdateReverse();

		/*** 爆発演出の更新 ***/
		UpdateExplosion();
	}
	
	/*** ポーズの更新 ***/
	UpdatePause();
	

#if ENABLE_LOOP == true
	if (GetKeyboardTrigger(DIK_RETURN)
		&& GetFade() == FADE_NONE)
	{
		SetFade(MODE_RESULT, FADE_TYPE_NORMAL);
	}
#endif
}

